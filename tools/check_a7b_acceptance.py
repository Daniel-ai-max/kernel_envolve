"""Check a design catalog, never run kernels or grant evaluator qualification."""

import argparse
import ast
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = ROOT / "acceptance" / "a7b"
PRIORITIES = {"P0", "P1", "P2"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def relative_path(value):
    path = Path(value)
    require(not path.is_absolute() and ".." not in path.parts, f"Unsafe path: {value}")
    return path


def check_catalog(catalog, inventory):
    require(catalog["schema"] == "a7b-acceptance-design-v1", "Unknown catalog schema")
    require(inventory["schema"] == "a7b-priority-source-v1", "Unknown source schema")
    require(catalog["status"] == "design_only", "Catalog must not grant qualification")
    require(set(catalog["profiles"]) == set(inventory["profiles"]), "Profile coverage mismatch")
    expected = {}
    for profile, source in inventory["profiles"].items():
        ids = [row["source_id"] for row in source["items"]]
        require(len(ids) == len(set(ids)), f"Duplicate source IDs in {profile}")
        for row in source["items"]:
            if row["priority"] in PRIORITIES:
                expected[profile, row["source_id"]] = (row["priority"], row["operator"])
    require(bool(expected), "Source inventory has no P0-P2 scope")
    actual, operator_ids, documents = {}, set(), set()
    for operator in catalog["operators"]:
        key = operator["id"]
        require(re.fullmatch(r"[a-z][a-z0-9-]+", key), f"Invalid operator ID: {key}")
        require(key not in operator_ids, f"Duplicate operator: {key}")
        operator_ids.add(key)
        require(operator["status"] == "design_only", f"{key}: design is not a PASS receipt")
        document = relative_path(operator["document"])
        require(document == Path("operators") / f"{key}.md", f"{key}: unexpected document")
        require(document not in documents, "Duplicate operator document")
        documents.add(document)
        for field in ("contract", "oracle", "integration", "holdout"):
            require(isinstance(operator[field], str) and operator[field].strip(), f"{key}: {field}")
        for field in ("outputs", "case_axes", "negative_controls", "gaps", "references"):
            require(
                isinstance(operator[field], list) and operator[field], f"{key}: missing {field}"
            )
        require(operator["performance"]["objective"], f"{key}: no timing boundary")
        require(operator["performance"]["guards"], f"{key}: no performance guards")
        require(operator["priorities"], f"{key}: no source priority")
        for profile, priority in operator["priorities"].items():
            pair = profile, operator["source_id"]
            require(pair not in actual, f"Duplicate assignment: {pair}")
            actual[pair] = (priority, operator["title"])
        for ref in operator["references"]:
            require(ref["repository"] in catalog["audited_sources"], f"{key}: unknown repository")
            relative_path(ref["path"])
            require(ref["kind"] in {"source", "test", "gate", "module_gate"}, "Unknown reference")
            require(ref["coverage_note"], f"{key}: reference needs coverage boundary")
            require(isinstance(ref["symbols"], list), f"{key}: symbols must be a list")
    require(
        actual == expected, f"Priority/source coverage mismatch: expected {expected}, got {actual}"
    )
    for name, source in catalog["audited_sources"].items():
        require(re.fullmatch(r"[0-9a-f]{40}", source["revision"]), f"{name}: unpinned revision")
    for key in ("required_instance_fields", "stages", "evidence"):
        require(catalog["policy"][key], f"Missing common policy: {key}")
    return len(operator_ids), len(actual)


def render_operator(operator, catalog):
    """Human-readable projection; catalog.json is the single editable specification."""
    lines = [
        f"# {operator['title']}",
        "",
        "<!-- Generated by tools/check_a7b_acceptance.py --render; edit catalog.json. -->",
        "",
        "状态：**验收设计已登记；尚未生成任务 adapter，也未运行 GPU 验收。**",
        "",
        f"来源行：{operator['source_id']}。优先级："
        + " · ".join(f"{p.upper()} {v}" for p, v in operator["priorities"].items())
        + "。未列出的 profile 不在该条目的本次范围内。",
        "",
        "本项与[公共规则](../README.md)一起使用；接入时固定实际 profile、源码、输入和阈值。",
    ]
    sections = [
        ("行为契约", operator["contract"]),
        ("必需输出与状态", operator["outputs"]),
        ("开发/full 输入覆盖轴", operator["case_axes"]),
        ("独立正确性参考", operator["oracle"]),
        ("集成验收", operator["integration"]),
        ("性能目标", operator["performance"]["objective"]),
        ("性能保护与计时边界", operator["performance"]["guards"]),
        ("独立确认集设计", operator["holdout"]),
        ("验证器负对照", operator["negative_controls"]),
        ("接入前待补齐", operator["gaps"]),
    ]
    for title, value in sections:
        lines.extend(["", f"## {title}", ""])
        lines.extend([f"- {entry}" for entry in value] if isinstance(value, list) else [value])
    lines.extend(["", "## 已核对的源码与复用入口", ""])
    for ref in operator["references"]:
        source = catalog["audited_sources"][ref["repository"]]
        url = f"{source['repository']}/blob/{source['revision']}/{ref['path']}"
        lines.extend(
            [
                f"- [{ref['repository']}:{ref['path']}]({url})（{ref['kind']}）",
                f"  — {ref['coverage_note']}。",
            ]
        )
        if ref["symbols"]:
            lines.append("  符号：" + "、".join(f"`{s}`" for s in ref["symbols"]) + "。")
    lines.extend(
        [
            "",
            "这些入口在目录的 audited_sources 版本静态核对；不是历史 E65/E98 的执行结果。",
            "换 baseline 时重新检查入口、实际后端、skip 条件、测试参数与必需 rank；",
            "测试名称存在不证明当前配置已覆盖。正式收据必须来自本轮完整测试和原始计时。",
            "",
        ]
    )
    return "\n".join(lines)


def check_sources(catalog, roots):
    """Read pinned Git objects and AST only. Do not import or execute external projects."""
    checked = set()
    for operator in catalog["operators"]:
        for ref in operator["references"]:
            repo = ref["repository"]
            if repo not in roots:
                continue
            root = Path(roots[repo]).resolve()
            revision = catalog["audited_sources"][repo]["revision"]
            relative_path(ref["path"])
            payload = subprocess.check_output(
                ["git", "-C", str(root), "show", f"{revision}:{ref['path']}"],
                stderr=subprocess.PIPE,
                timeout=30,
            )
            tree = ast.parse(payload.decode("utf-8"))
            if ref["kind"] in {"gate", "module_gate"}:
                symbols = {
                    key.value
                    for node in ast.walk(tree)
                    if isinstance(node, ast.Dict)
                    for key in node.keys
                    if isinstance(key, ast.Constant) and isinstance(key.value, str)
                }
            else:
                symbols = {
                    node.name
                    for node in ast.walk(tree)
                    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
                }
            missing = set(ref["symbols"]) - symbols
            require(not missing, f"{repo}:{ref['path']}: missing symbols {sorted(missing)}")
            checked.add((repo, ref["path"]))
    return len(checked)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, default=DEFAULT)
    parser.add_argument("--core", type=Path, help="Optional local apodex-core Git object store")
    parser.add_argument("--megatron", type=Path, help="Optional local Megatron Git object store")
    parser.add_argument("--render", action="store_true", help="Regenerate operator Markdown only")
    args = parser.parse_args()
    try:
        catalog = json.loads((args.directory / "catalog.json").read_text())
        inventory = json.loads((args.directory / "source-inventory.json").read_text())
        counts = check_catalog(catalog, inventory)
        for operator in catalog["operators"]:
            file = args.directory / relative_path(operator["document"])
            expected = render_operator(operator, catalog)
            if args.render:
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_text(expected)
            else:
                require(file.read_text() == expected, f"Stale document: {file}; run --render")
        roots = {k: v for k, v in {"core": args.core, "megatron": args.megatron}.items() if v}
        files = check_sources(catalog, roots)
    except (ValueError, KeyError, TypeError, OSError, subprocess.SubprocessError) as exc:
        parser.exit(1, f"Design check failed: {exc}\n")
    print(
        json.dumps(
            {
                "design_check": "passed",
                "operators": counts[0],
                "profile_assignments": counts[1],
                "source_repositories_checked": sorted(roots),
                "source_files_checked": files,
                "gpu_validation": "not_run",
                "qualification": "none",
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
