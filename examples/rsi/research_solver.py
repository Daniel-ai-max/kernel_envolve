"""Example solver adapter: an operator-owned decision command writes decision.json.

Use --model-command as the last argument. The command is trusted infrastructure,
not generated by RSI. Run generated candidates in an externally isolated worker.
"""

import argparse
import json
import sys
from pathlib import Path

from kernel_envolve.rsi.model import read
from kernel_envolve.rsi.process import invoke
from kernel_envolve.rsi.research import report_records, run
from kernel_envolve.storage import write_json


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--actions", type=int, default=2)
    parser.add_argument("--model-seconds", type=float, default=55)
    parser.add_argument("--evaluation-seconds", type=float, default=30)
    parser.add_argument("--model-command", nargs=argparse.REMAINDER, required=True)
    args = parser.parse_args()
    if not args.model_command:
        parser.error("A trusted decision command is required")
    packet = json.load(sys.stdin)
    directory = Path.cwd()
    sequence = 0

    def decide(request, timeout):
        nonlocal sequence
        sequence += 1
        destination = directory / f"decision-{sequence}"
        destination.mkdir()
        invoke(args.model_command, destination, request, timeout, device="cpu")
        return read(destination / "decision.json", 65536)

    trace = run(
        packet,
        directory,
        decide,
        max_actions=args.actions,
        model_seconds=args.model_seconds,
        evaluation_seconds=args.evaluation_seconds,
    )
    write_json(
        directory / "research-reports.json", report_records(packet["task"], trace, directory)
    )


if __name__ == "__main__":
    main()
